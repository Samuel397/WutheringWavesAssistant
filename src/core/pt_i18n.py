def _escape_ocr_token(token: str) -> str:
    return "".join(_ACCENTED_OCR_CHARS.get(char.casefold(), re.escape(char)) for char in token)


def pt_fuzzy_regex(pattern: str) -> str:
    """Make a hand-written PT regex tolerant of accent loss/substitution."""
    return "".join(_ACCENTED_OCR_CHARS.get(char.casefold(), char) for char in pattern)


def _flex_ws(text: str) -> str:
    return r"\s*?".join(_escape_ocr_token(part) for part in re.split(r"\s+", text.strip()))


def _ocr_pattern(text: str) -> str:
    pattern = _flex_ws(text)
    # TextMap variables are rendered as numbers/names on screen.  Preserve the
    # official surrounding text while accepting the runtime-substituted value.
    pattern = re.sub(r"\\\{[^{}]+\\\}", r".*?", pattern)
    # The multiplication glyph is a frequent OCR substitution.
    return pattern.replace("×", r"[×xX*]")


def pt_regex(key: str) -> str:
    """Return one anchored, whitespace-tolerant pattern for an i18n key."""
    values = PT_OFFICIAL_TEXT.get(key)
    if not values:
        reason = PT_I18N_UNRESOLVED.get(key, "unknown Portuguese OCR key")
        raise KeyError(f"Mapeamento OCR em português indisponível para {key!r}: {reason}")
    patterns = [_ocr_pattern(value) for value in values]
    return rf"^(?:{'|'.join(patterns)})$"
